const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
async function run() {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'simhub-desktop-'));
  const env = Object.fromEntries(Object.entries(process.env).filter(([key]) => !key.startsWith('SIMHUB_')));
  env.SIMHUB_DATA_DIR = directory;
  delete env.ELECTRON_RUN_AS_NODE;
  let app;
  try {
    app = await electron.launch({ ...(process.env.SIMHUB_TEST_PACKAGED ? { executablePath: process.env.SIMHUB_TEST_PACKAGED, args: [] } : { args: [path.resolve(__dirname, '..')] }), env });
    const page = await app.firstWindow();
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.getByRole('heading', { name: 'Platz für deine Pläne.' }).waitFor();
    await page.locator('#event-count').filter({ hasText: '0 Termine' }).waitFor();
    const security = await app.evaluate(({ BrowserWindow }) => { const prefs = BrowserWindow.getAllWindows()[0].webContents.getLastWebPreferences(); return { node: prefs.nodeIntegration, isolation: prefs.contextIsolation, sandbox: prefs.sandbox }; });
    assert.deepEqual(security, { node: false, isolation: true, sandbox: true });
    assert.equal(await page.evaluate(() => typeof window.require), 'undefined');
    assert.equal(await page.locator('img.brand-icon').evaluate(image => image.complete && image.naturalWidth === 1024), true);
    // Logo navigation and same-document fragments must not revoke IPC access.
    const originalURL = page.url();
    await page.getByRole('button', { name: 'Kalender öffnen', exact: true }).click();
    assert.equal(page.url(), originalURL);
    await page.evaluate(() => { window.location.hash = 'calendar'; });
    assert.equal((await page.evaluate(() => window.calendarAPI.load())).ok, true);
    await page.getByRole('button', { name: /Neuer Termin/ }).click();
    await page.locator('#event-title').fill('Projektbesprechung');
    const start = new Date(); start.setHours(10, 0, 0, 0);
    const local = d => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}T${String(d.getHours()).padStart(2, '0')}:00`;
    await page.locator('#event-start').fill(local(start));
    await page.locator('#event-end').fill(local(new Date(+start + 3600000)));
    await page.locator('#event-calendar').selectOption('2');
    await page.locator('#event-location').fill('Büro');
    await page.locator('#save-event').click();
    await page.locator('#event-count').filter({ hasText: '1 Termine' }).waitFor();
    await page.getByRole('button', { name: /Projektbesprechung/ }).first().click();
    await page.locator('#event-title').fill('Projektplanung');
    await page.locator('#event-location').fill('');
    await page.locator('#save-event').click();
    await page.getByRole('button', { name: /Projektplanung/ }).first().waitFor();
    await page.reload();
    await page.getByRole('button', { name: /Projektplanung/ }).first().waitFor();
    await page.getByRole('button', { name: 'Woche', exact: true }).click();
    assert.equal(await page.locator('.week-grid .day-cell').count(), 7);
    await page.getByRole('button', { name: 'Agenda', exact: true }).click();
    await page.locator('.agenda-event').waitFor();
    await page.getByRole('button', { name: 'Monat', exact: true }).click();
    assert.equal(await page.locator('.day-cell').count(), 42);
    await page.locator('#search').fill('keine-treffer-123');
    await page.getByText('Keine passenden Termine. Versuche einen anderen Suchbegriff.').waitFor();
    await page.locator('#search').fill('');
    await page.locator('.month-grid').waitFor();
    const filters = page.locator('.calendar-filter input');
    await filters.nth(1).uncheck();
    assert.equal(await page.locator('.event-chip').count(), 0);
    await filters.nth(1).check();
    await page.locator('.event-chip').waitFor();
    await page.locator('#assistant-open').click();
    await page.locator('#assistant-prompt').fill('Morgen um 14:30 Uhr Kaffee 30 Minuten');
    await page.locator('#local-draft').click();
    await page.locator('#event-dialog').waitFor();
    assert.equal(await page.locator('#event-id').inputValue(), '');
    assert.match(await page.locator('#event-start').inputValue(), /T14:30$/);
    await page.locator('#event-dialog [data-close]').first().click();
    assert.equal(JSON.parse(await fs.readFile(path.join(directory, 'calendar-v2.json'), 'utf8')).events.length, 1);
    // Test hostile content stays literal rather than becoming executable markup.
    await page.locator('#new-event').click();
    await page.locator('#event-title').fill('<img src=x onerror=alert(1)>');
    await page.locator('#save-event').click();
    await page.locator('#event-count').filter({ hasText: '2 Termine' }).waitFor();
    assert.equal(await page.locator('#calendar img').count(), 0);
    await page.getByRole('button', { name: /<img src=x/ }).first().click();
    page.once('dialog', dialog => dialog.accept());
    await page.locator('#delete-event').click();
    await page.locator('#event-count').filter({ hasText: '1 Termine' }).waitFor();
    // Exercise settings and native backup dialogs through their real IPC handlers.
    await page.locator('#settings').click();
    await page.locator('#ai-provider').selectOption('ollama');
    await page.locator('#ai-model').fill('test-local-model');
    await page.locator('#ai-settings-save').click();
    await page.locator('#settings-ai-status').filter({ hasText: 'test-local-model' }).waitFor();
    await page.locator('#ai-provider').selectOption('off');
    await page.locator('#ai-settings-save').click();
    await page.locator('#settings-ai-status').filter({ hasText: 'Kein KI-Dienst' }).waitFor();
    const backupPath = path.join(directory, 'test-backup.json');
    await app.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }); }, backupPath);
    await page.locator('#export').click();
    await page.getByText('Backup exportiert.', { exact: true }).waitFor();
    const backup = JSON.parse(await fs.readFile(backupPath, 'utf8'));
    assert.equal(backup.events.length, 1);
    backup.events[0].title = 'Wiederhergestellter Termin';
    await fs.writeFile(backupPath, JSON.stringify(backup));
    await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); dialog.showMessageBox = async () => ({ response: 1 }); }, backupPath);
    await page.locator('#import').click();
    await page.getByText('Backup wiederhergestellt.', { exact: true }).waitFor();
    assert.ok((await fs.readdir(directory)).some(file => file.startsWith('before-import-')));
    assert.equal(JSON.parse(await fs.readFile(path.join(directory, 'calendar-v2.json'), 'utf8')).events[0].title, 'Wiederhergestellter Termin');
    const draftPath = path.join(directory, 'agent-draft.json');
    await fs.writeFile(draftPath, JSON.stringify({ ...backup.events[0], id: 'model-controlled-id', title: 'Agenten-Vorschlag' }));
    await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, draftPath);
    await page.locator('#open-draft').click();
    await page.locator('#event-title').filter({ visible: true }).waitFor();
    assert.equal(await page.locator('#event-title').inputValue(), 'Agenten-Vorschlag');
    assert.equal(await page.locator('#event-id').inputValue(), '');
    await page.locator('#event-dialog [data-close]').first().click();
    assert.equal(JSON.parse(await fs.readFile(path.join(directory, 'calendar-v2.json'), 'utf8')).events.length, 1);
    await page.evaluate(async () => { const loaded = await window.calendarAPI.load(); const event = loaded.value.events[0]; await window.calendarAPI.save({ ...event, title: 'Projektplanung' }); });
    // Seed only the isolated test directory for the visual review screenshot.
    await page.evaluate(async () => {
      const today = new Date();
      for (const [offset, hour, title, calendarId, location] of [[0, 14, 'Zeit für mich', '1', ''], [1, 11, 'Ideen & Austausch', '2', 'Studio'], [3, 18, 'Abend mit Freunden', '4', ''], [6, 9, 'Neue Perspektiven', '5', 'Unterwegs'], [-2, 16, 'Zeit mit der Familie', '3', '']]) {
        const start = new Date(today.getFullYear(), today.getMonth(), today.getDate() + offset, hour);
        const result = await window.calendarAPI.save({ title, calendarId, start: start.toISOString(), end: new Date(+start + 3600000).toISOString(), location });
        if (!result.ok) throw new Error(result.error);
      }
    });
    await page.reload();
    await page.locator('#event-count').filter({ hasText: '6 Termine' }).waitFor();
    await fs.mkdir(path.resolve('test-results'), { recursive: true });
    await page.screenshot({ path: path.resolve('test-results/calendar-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 800, height: 700 });
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
    assert.equal(overflow, false);
    await page.screenshot({ path: path.resolve('test-results/calendar-compact.png'), fullPage: true });
    assert.deepEqual(errors, []);
    console.log('Desktop-Test bestanden: Sandbox, CRUD, Persistenz, Ansichten, Suche, Filter, Entwürfe, Backups, Einstellungen, XSS und kompaktes Layout.');
  } finally { if (app) await app.close(); await fs.rm(directory, { recursive: true, force: true }); }
}
run().catch(error => { console.error(error); process.exitCode = 1; });
